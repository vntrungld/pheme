//! One row per key: name, USB HID usage (page 0x07), Linux evdev code, Windows set-1 scancode.
//! Sources: USB HID Usage Tables §10, linux/input-event-codes.h, Microsoft scancode set 1.
//! `win == None` means the key needs special handling on Windows (Pause) or has no scancode.

pub struct Entry {
    pub name: &'static str,
    pub hid: u16,
    pub evdev: u16,
    /// (scancode, extended)
    pub win: Option<(u16, bool)>,
}

const fn e(name: &'static str, hid: u16, evdev: u16, sc: u16) -> Entry {
    Entry {
        name,
        hid,
        evdev,
        win: Some((sc, false)),
    }
}

const fn x(name: &'static str, hid: u16, evdev: u16, sc: u16) -> Entry {
    Entry {
        name,
        hid,
        evdev,
        win: Some((sc, true)),
    }
}

const fn n(name: &'static str, hid: u16, evdev: u16) -> Entry {
    Entry {
        name,
        hid,
        evdev,
        win: None,
    }
}

