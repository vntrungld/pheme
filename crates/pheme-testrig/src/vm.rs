//! The runner's hands on the VMs: `virsh` and `ssh`, with every failure
//! typed as a [`RigError`] so that no caller can turn an infrastructure
//! problem into a product FAIL by accident.

use std::process::Command;

use crate::verdict::Verdict;

/// Something about the rig, not about pheme, went wrong.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RigError(pub String);

impl std::fmt::Display for RigError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "rig error: {}", self.0)
    }
}

impl std::error::Error for RigError {}

impl RigError {
    /// Always INCONCLUSIVE: see [`Verdict::from_rig_error`].
    pub fn verdict(&self) -> Verdict {
        Verdict::from_rig_error(&self.0)
    }
}

/// Runs a command and returns its stdout, or a [`RigError`] naming it.
pub fn run(cmd: &mut Command) -> Result<String, RigError> {
    let shown = format!("{cmd:?}");
    let out = cmd
        .output()
        .map_err(|e| RigError(format!("could not run {shown}: {e}")))?;
    if !out.status.success() {
        return Err(RigError(format!(
            "{shown} exited {}: {}",
            out.status,
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

pub fn virsh(args: &[&str]) -> Result<String, RigError> {
    run(Command::new("virsh")
        .arg("-c")
        .arg("qemu:///system")
        .args(args))
}

/// The guest's IPv4 address from `virsh domifaddr` output, if it has a lease.
pub fn parse_domifaddr(out: &str) -> Option<String> {
    out.lines().find_map(|l| {
        let cols: Vec<&str> = l.split_whitespace().collect();
        match cols.as_slice() {
            [_, _, "ipv4", addr, ..] => addr.split('/').next().map(str::to_string),
            _ => None,
        }
    })
}

pub fn vm_ip(domain: &str) -> Result<Option<String>, RigError> {
    Ok(parse_domifaddr(&virsh(&["domifaddr", domain])?))
}

/// The rig's own key, generated by the provisioning scripts. Paths are
/// relative to the repository root, where `testrig/run` starts the runner.
pub const RIG_KEY: &str = "testrig/id_rig";

/// What a command run over ssh produced. Its exit code is the product's
/// answer; ssh's own failures never get this far.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Remote {
    pub code: i32,
    pub stdout: String,
    pub stderr: String,
}

impl Remote {
    pub fn ok(&self) -> bool {
        self.code == 0
    }
}

/// ssh exits 255 for its own failures, and a remote command killed by a
/// signal has no code at all; both are the rig's problem, not pheme's.
pub fn remote_result(code: Option<i32>, stdout: &str, stderr: &str) -> Result<Remote, RigError> {
    match code {
        Some(255) | None => Err(RigError(format!("ssh failed: {}", stderr.trim()))),
        Some(code) => Ok(Remote {
            code,
            stdout: stdout.to_string(),
            stderr: stderr.to_string(),
        }),
    }
}

/// Options shared by ssh and scp: the rig's key, and no host-key prompt --
/// these machines are rebuilt from snapshots, so a changing host key is
/// expected rather than suspicious.
fn with_rig_options(cmd: &mut Command) -> &mut Command {
    cmd.args(["-i", RIG_KEY])
        .args(["-o", "StrictHostKeyChecking=no"])
        .args(["-o", "UserKnownHostsFile=/dev/null"])
        .args(["-o", "LogLevel=ERROR"])
        .args(["-o", "ConnectTimeout=5"])
}

/// Runs `command` on the guest as `user`.
pub fn ssh(ip: &str, user: &str, command: &str) -> Result<Remote, RigError> {
    let out = with_rig_options(&mut Command::new("ssh"))
        .arg(format!("{user}@{ip}"))
        .arg(command)
        .output()
        .map_err(|e| RigError(format!("could not run ssh: {e}")))?;
    remote_result(
        out.status.code(),
        &String::from_utf8_lossy(&out.stdout),
        &String::from_utf8_lossy(&out.stderr),
    )
}

/// Copies a local file to `remote` on the guest.
pub fn scp(local: &std::path::Path, ip: &str, user: &str, remote: &str) -> Result<(), RigError> {
    run(with_rig_options(&mut Command::new("scp"))
        .arg(local)
        .arg(format!("{user}@{ip}:{remote}")))
    .map(drop)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The production change that breaks this: take the first address column
    /// regardless of protocol, which returns an IPv6 link-local address the
    /// rig's ssh cannot use, and every row goes INCONCLUSIVE.
    #[test]
    fn the_ipv4_lease_is_read_from_domifaddr() {
        let out = " Name       MAC address          Protocol     Address\n\
                   -------------------------------------------------------\n \
                   vnet3      52:54:00:12:34:56    ipv6         fe80::1/64\n \
                   vnet3      52:54:00:12:34:56    ipv4         192.168.140.57/24\n";
        assert_eq!(parse_domifaddr(out), Some("192.168.140.57".to_string()));
    }

    /// ssh exits 255 when ssh itself failed; anything else is the remote
    /// command's own status. The production change that breaks this: treat
    /// every non-zero exit alike, which charges a dropped connection to pheme
    /// as a FAIL -- or, the other way, excuses a real failure as a rig error.
    #[test]
    fn ssh_s_own_failure_is_a_rig_error_and_the_command_s_is_not() {
        assert!(remote_result(Some(255), "", "Connection timed out").is_err());
        assert!(remote_result(None, "", "killed by signal").is_err());
        let r = remote_result(Some(1), "out", "err").expect("the command ran");
        assert_eq!(r.code, 1);
        assert_eq!(r.stdout, "out");
    }

    #[test]
    fn no_lease_yet_is_none() {
        assert_eq!(
            parse_domifaddr(" Name  MAC address  Protocol  Address\n----\n"),
            None
        );
    }
}
